"""Independent identities for Laurent-to-polynomial row normalization."""
from numbers import Integral

from css_decoupling.algebra.laurent import Matrix, Poly, eye


def verify_normalization(witness):
    """Verify invertible substitutions, exact row change and polynomial unity.

    If g_0=1+Xh and g*b=X^M with polynomial h,b, then the polynomial
    ideal generated by g contains one by a finite geometric-series identity.
    This checks the compact identity without constructing a huge expansion.
    It does not certify a completion matrix or call its constructor.
    """
    f, g, U, V = witness.original, witness.row, witness.change, witness.change_inverse
    if not isinstance(f, Matrix) or f.nrows != 1 or f.ncols < 1:
        raise ValueError("Invalid original row")
    r, n, D = f.ring, f.ncols, f.ring.D
    if any(not isinstance(M, Matrix) or M.ring != r for M in (g, U, V)):
        raise ValueError("Inconsistent coefficient rings")
    if g.shape != f.shape or U.shape != (n, n) or V.shape != (n, n):
        raise ValueError("Invalid row-change dimensions")
    B, C = witness.exponents, witness.inverse_exponents
    for A in (B, C):
        if len(A) != D or any(len(row) != D for row in A):
            raise ValueError("Invalid exponent map dimensions")
        if any(isinstance(a, bool) or not isinstance(a, Integral) for row in A for a in row):
            raise ValueError("Exponent maps must be integral")
    for A, inverse in ((B, C), (C, B)):
        if any(sum(A[i][k] * inverse[k][j] for k in range(D)) != int(i == j)
               for i in range(D) for j in range(D)):
            raise ValueError("Exponent maps are not inverse integer automorphisms")
    transformed = Matrix(r, 1, n)
    for ij, polynomial in f.entries.items():
        terms = {}
        for exponent, coefficient in polynomial.terms.items():
            image = tuple(sum(B[i][k] * exponent[k] for k in range(D)) for i in range(D))
            terms[image] = (terms.get(image, 0) + coefficient) % r.p
        transformed[ij] = Poly(r, terms)
    if transformed * U != g or U * V != eye(r, n) or V * U != eye(r, n):
        raise ValueError("Row change is not the claimed invertible transformation")
    M, b, h = witness.saturation_power, witness.saturation_bezout, witness.face_remainder
    if isinstance(M, bool) or not isinstance(M, Integral) or M < 0:
        raise ValueError("Saturation power must be a nonnegative integer")
    if not isinstance(b, Matrix) or b.ring != r or b.shape != (n, 1):
        raise ValueError("Invalid saturation Bezout column")
    if not isinstance(h, Poly) or h.ring != r:
        raise ValueError("Invalid face remainder")
    if any(e_i < 0 for polynomial in (*g.entries.values(), *b.entries.values(), h)
           for e in polynomial.terms for e_i in e):
        raise ValueError("Normalization witnesses must be ordinary polynomials")
    X = r.monomial((1,) * D)
    if g[0, 0] != 1 + X * h or g * b != Matrix.from_rows(r, [[X ** int(M)]]):
        raise ValueError("Polynomial unimodularity witness failed")
    if any(any(e_i < 1 for e_i in e) for (i, j), polynomial in g.entries.items() if j
           for e in polynomial.terms):
        raise ValueError("Other row entries must vanish on every coordinate face")
    return True
